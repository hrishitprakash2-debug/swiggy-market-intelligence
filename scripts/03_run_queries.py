"""
03_run_queries.py — Execute every .sql file in sql/queries/ against the warehouse.

Exports each result set to output/sql_results/<name>.csv and writes
output/sql_findings.md (row counts + the first rows of each result) so the SQL
layer is reproducible by anyone who clones the repo.
"""
from __future__ import annotations

import sqlite3
import time
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DB = ROOT / "data" / "swiggy.db"
QDIR = ROOT / "sql" / "queries"
OUT = ROOT / "output" / "sql_results"
OUT.mkdir(parents=True, exist_ok=True)

con = sqlite3.connect(DB)
files = sorted(QDIR.glob("*.sql"))
print(f"running {len(files)} queries against {DB.name}\n")

md = ["# SQL results index", "",
      "Auto-generated by `scripts/03_run_queries.py`. Each file in `sql/queries/` "
      "runs against the SQLite star schema in `sql/schema.sql`.", ""]
failures, total_time = [], 0.0

for f in files:
    sql = f.read_text(encoding="utf-8")
    t0 = time.perf_counter()
    try:
        df = pd.read_sql_query(sql, con)
    except Exception as exc:                       # noqa: BLE001
        failures.append((f.stem, str(exc)))
        print(f"  FAIL {f.stem}: {exc}")
        continue
    dt = (time.perf_counter() - t0) * 1000
    total_time += dt
    df.to_csv(OUT / f"{f.stem}.csv", index=False, encoding="utf-8")

    q_label = sql.splitlines()[0].replace("-- ", "")
    print(f"  {f.stem:<32} rows={len(df):>4}  cols={df.shape[1]:>2}  {dt:6.1f} ms")

    md += [f"## {f.stem}", "", f"_{q_label}_", "",
           f"rows: **{len(df)}** · runtime: {dt:.0f} ms", "",
           df.head(8).to_markdown(index=False), ""]

con.close()

md += ["---", "", f"queries run: {len(files) - len(failures)}/{len(files)} · "
       f"total time: {total_time/1000:.2f}s · failures: {len(failures)}", ""]
(ROOT / "output" / "sql_findings.md").write_text("\n".join(md), encoding="utf-8")

print(f"\n{len(files) - len(failures)}/{len(files)} queries OK in {total_time/1000:.2f}s")
if failures:
    print("FAILURES:", failures)
